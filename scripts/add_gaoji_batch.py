def append(path, items):
    data = json.load(io.open(path, encoding="utf-8"))
    have = {x["id"] for x in data}
    added = 0
    for it in items:
        if it["id"] in have:
            continue
        data.append(it)
        added += 1
    io.open(path, "w", encoding="utf-8").write(json.dumps(data, ensure_ascii=False, indent=1) + "\n")
    print("%s：新增 %d 题，共 %d 题" % (os.path.basename(path), added, len(data)))

